-- 密钥明文可反复查看（对齐 sub2api 的做法）。
--
-- ---------------------------------------------------------------------------
-- 为什么改
-- ---------------------------------------------------------------------------
-- 原设计是"明文只显示一次，丢了就轮换"。实际使用中这很别扭：
-- 用户配好客户端、过几天想在另一台机器上再加一个客户端，就必须轮换 Key ——
-- 而那会把旧客户端全部踢下线。
--
-- sub2api 的做法是库里存一份可再读的明文，列表里随时能复制。按用户要求对齐。
--
-- ---------------------------------------------------------------------------
-- 安全取舍（写清楚，避免后来的人以为是漏了）
-- ---------------------------------------------------------------------------
-- 这确实降低了"库被读走"的门槛：拿到库就拿到所有下游 Key。
-- 但要注意它**不改变上游凭据的安全**：账号凭据（access_token / API Key）
-- 仍然是主密钥加密的，那把主密钥只在网关进程里。
-- 下游 Key 只是"调用本网关的凭证"，泄露后的处置是"在界面上轮换"，
-- 而轮换不需要碰上游账号。
--
-- 代价与收益的权衡由产品决定（用户明确选择了可用性）。
-- 如果将来要收紧，正确做法是改成"加密存 + 点显示才解密"，而不是删列。

ALTER TABLE api_keys ADD COLUMN key_plaintext TEXT;

COMMENT ON COLUMN api_keys.key_plaintext IS
    '密钥明文，供界面反复查看与复制。上游凭据仍由主密钥加密，与此列无关。';

-- 老数据补不回来：它们的明文只在创建时出现过一次，已经丢了。
-- 这里留 NULL，界面显示"仅前缀可用，请轮换"，不假装能复制。
