-- 每个分组可以指定「探活用哪个模型」。
--
-- ---------------------------------------------------------------------------
-- 为什么需要它
-- ---------------------------------------------------------------------------
-- 探活默认按「免费优先」挑模型（探针会真实消耗积分，不该拿付费档试）。
-- 但这有个盲区：**免费模型通了不代表真实模型能通**。
--
-- 典型场景：
--   · 分组里只挂了推理模型，免费档是另一个轻量模型 —— 探活一直绿，
--     真实请求却因为该号没有推理模型权限而失败；
--   · 某个号被单独限权，只有特定模型可用。
--
-- 所以允许管理员指定"用哪个模型探活"，让探针贴近真实用法。
--
-- ---------------------------------------------------------------------------
-- 语义
-- ---------------------------------------------------------------------------
-- NULL 或空串 = 不指定，走网关的「免费优先」策略（默认行为，保持不变）。
-- 有值 = 用这个对外模型名探活。
--
-- 存的是**对外模型名**（`models.canonical_name`），不是上游名：
-- 管理员认得的是对外名，上游叫什么属于渠道内部细节。

ALTER TABLE channels ADD COLUMN IF NOT EXISTS probe_model TEXT;

COMMENT ON COLUMN channels.probe_model IS
    '探活使用的对外模型名；NULL/空 = 由网关按「免费优先」自动挑。';
