-- 分组级模型白名单：这个分组对外只暴露哪些模型。
--
-- ---------------------------------------------------------------------------
-- 为什么需要它（与账号级 model_allow 的区别）
-- ---------------------------------------------------------------------------
-- 账号级 `model_allow` 回答的是"这个号**能跑**哪些模型"（凭据/套餐限制），
-- 分组级回答的是"这个分组**愿意卖**哪些模型"（产品策略）。
--
-- 典型用法：WorkBuddy 分组下面那批号的凭据技术上能跑十几家模型，
-- 但运营只想让它对外提供 ds 与 glm —— 其余的即使能跑也不该出现在模型广场里。
-- 用账号级字段做不到这件事：那是"能力"，不是"策略"；
-- 而且一个分组下几十个号，逐个配置既易漏也难维护。
--
-- ---------------------------------------------------------------------------
-- 语义
-- ---------------------------------------------------------------------------
-- NULL 或空数组 = **不限制**（该分组下账号能跑的模型全部对外）。
-- 这与"白名单为空 = 一个都不让用"相反 —— 后者会让新建分组默认不可用，
-- 是个很难排查的坑。所以显式用 NULL 表示"未配置"。
--
-- 匹配的是**对外模型名**（`models.canonical_name`），不是上游名：
-- 对外暴露的是统一名字，上游叫什么是内部细节。

ALTER TABLE channels ADD COLUMN IF NOT EXISTS model_allow TEXT[];

COMMENT ON COLUMN channels.model_allow IS
    '分组对外暴露的模型白名单；NULL/空 = 不限制。与账号级 model_allow（能力）不同，这是产品策略。';
